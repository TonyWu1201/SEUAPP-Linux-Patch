#!/bin/bash
# 企业微信 (wwlocal) —— 将修补后的 deb 重新打包为 Arch Linux 包（.pkg.tar.zst）
#
# 用法: ./pack_arch.sh <已修补的deb> [输出.pkg.tar.zst]
#   e.g. ./pack_arch.sh ~/weworklocal_2.6.290000.49_1648784689.patched4.deb
#
# 说明:
#   - 在 Debian/Ubuntu 构建机上做"重打包"，产物供 Arch 安装:
#       sudo pacman -U wwlocal-2.6.290000.4-1-x86_64.pkg.tar.zst
#   - 需要: fakeroot、zstd、tar；bsdtar 用于生成 .MTREE（无则跳过，不影响安装）。
#   - Arch 原生重建(从原始 deb + 本目录补丁脚本)请用本目录的 PKGBUILD +
#     makepkg；两条路径产物等价。
#   - 包内容与修补后的 deb 完全一致（字节级），仅封装格式与安装脚本适配 pacman。
set -euo pipefail

DEB="${1:?用法: ./pack_arch.sh <patched.deb> [输出.pkg.tar.zst]}"
[ -f "$DEB" ] || { echo "错误: 找不到 $DEB" >&2; exit 1; }
HERE="$(cd "$(dirname "$0")" && pwd)"
TOOLS="$HERE/.buildtools/root"

PKGNAME="wwlocal"
PKGVER="2.6.290000.4-1"
CARCH="x86_64"
OUT="${2:-$HERE/$PKGNAME-$PKGVER-$CARCH.pkg.tar.zst}"
APPDIR='opt/企业微信'

export LANG=C.UTF-8 LC_ALL=C.UTF-8
umask 022

WORK="$(mktemp -d /tmp/wwpatch-arch.XXXXXX)"
trap 'rm -rf "$WORK"' EXIT

for t in fakeroot tar zstd du gzip; do
    command -v "$t" >/dev/null 2>&1 || {
        echo "错误: 缺少 $t（Debian/Ubuntu: sudo apt install fakeroot zstd；Arch: base-devel + zstd）" >&2
        exit 1
    }
done

BSDTAR=""
if command -v bsdtar >/dev/null 2>&1; then
    BSDTAR="$(command -v bsdtar)"
elif [ -x "$TOOLS/usr/bin/bsdtar" ]; then
    BSDTAR="$TOOLS/usr/bin/bsdtar"
fi

extract_deb() { # $1=deb  $2=目标目录
    if command -v dpkg-deb >/dev/null 2>&1; then
        dpkg-deb -x "$1" "$2"
        return
    fi
    # 无 dpkg 时用 ar+tar（binutils/tar 各发行版均自带）
    local t
    t="$(mktemp -d)"
    (cd "$t" && ar x "$1")
    tar -xf "$t"/data.tar.* -C "$2"
    rm -rf "$t"
}

# ---- 1. 解包载荷 --------------------------------------------------------
echo "[1/3] 解包载荷: $DEB"
PKGDIR="$WORK/pkg"
mkdir -p "$PKGDIR"
extract_deb "$DEB" "$PKGDIR"
[ -x "$PKGDIR/$APPDIR/wwlocal" ] || { echo "错误: 载荷中找不到 $APPDIR/wwlocal（不是企业微信包？）" >&2; exit 1; }
# 防御性恢复 setuid：dpkg-deb 会保留，但 ar+tar 回退路径可能剥离
[ -f "$PKGDIR/$APPDIR/chrome-sandbox" ] && chmod 4755 "$PKGDIR/$APPDIR/chrome-sandbox"

# ---- 2. 生成元数据 ------------------------------------------------------
echo "[2/3] 生成 .PKGINFO / .BUILDINFO / .INSTALL / .MTREE"
SIZE="$(du -sb "$PKGDIR" | cut -f1)"
BUILDDATE="$(date +%s)"
PACKAGER="${PACKAGER:-wwlocal-repack}"

cat >"$PKGDIR/.PKGINFO" <<EOF
# Generated by pack_arch.sh (企业微信 wwlocal 重打包)
pkgname = $PKGNAME
pkgbase = $PKGNAME
xdata = pkgtype=pkg
pkgver = $PKGVER
pkgdesc = 企业微信 (weworklocal) 桌面客户端 —— glibc 兼容修补重打包版
url = https://work.weixin.qq.com/
builddate = $BUILDDATE
packager = $PACKAGER
size = $SIZE
arch = $CARCH
license = custom:ISC
depend = gtk3
depend = glib2
depend = pango
depend = cairo
depend = gdk-pixbuf2
depend = at-spi2-core
depend = nss
depend = libx11
depend = libxcb
depend = libxcomposite
depend = libxcursor
depend = libxdamage
depend = libxext
depend = libxfixes
depend = libxi
depend = libxrender
depend = libxrandr
depend = libxtst
depend = libxss
depend = alsa-lib
depend = libcups
depend = dbus
depend = expat
depend = xdg-utils
optdepend = libayatana-appindicator: 系统托盘图标（若 Electron 8 未识别，可试 AUR 的 libappindicator-gtk3）
optdepend = libsecret: 凭据（密码）存储
optdepend = libnotify: 桌面通知
optdepend = mesa: OpenGL 硬件加速
optdepend = noto-fonts-cjk: 中文字体（系统未安装中文字体时）
EOF

cat >"$PKGDIR/.BUILDINFO" <<EOF
format = 2
pkgname = $PKGNAME
pkgbase = $PKGNAME
pkgver = $PKGVER
pkgarch = $CARCH
packager = $PACKAGER
builddate = $BUILDDATE
builddir = /tmp
buildenv = pack_arch.sh
options = !strip
EOF

cp -f "$HERE/wwlocal.install" "$PKGDIR/.INSTALL"

if [ -n "$BSDTAR" ]; then
    # 与 makepkg 相同的方式生成 .MTREE（pacman 7 会以它作为包内文件清单，
    # 因此必须包含全部文件；缺失或错误会导致 pacman 静默跳过解包！）
    (
        cd "$PKGDIR"
        export LC_COLLATE=C
        shopt -s dotglob globstar
        printf '%s\0' **/* | LANG=C fakeroot "$BSDTAR" -cnf - --format=mtree \
            --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' \
            --null --files-from - --exclude .MTREE
    ) | gzip -n -c >"$WORK/.MTREE.gz"
    mv "$WORK/.MTREE.gz" "$PKGDIR/.MTREE"
else
    echo "  警告: 未找到 bsdtar，不生成 .MTREE。" >&2
    echo "        pacman 将退回到按归档扫描文件清单；建议安装 bsdtar(libarchive-tools) 后重打包。" >&2
fi

# ---- 3. 打包 ------------------------------------------------------------
echo "[3/3] 打包 -> $OUT"
MEMBERS=(.PKGINFO .BUILDINFO .INSTALL)
[ -n "$BSDTAR" ] && MEMBERS+=(.MTREE)
MEMBERS+=(opt usr)
(
    cd "$PKGDIR"
    fakeroot tar --format=gnu -cf - "${MEMBERS[@]}"
) | zstd -q -T0 -19 -f -o "$OUT" -
echo
echo "完成: $OUT ($(du -h "$OUT" | cut -f1))"
echo "安装: sudo pacman -U '$OUT'"

# ---- 校验（有 pacman 时输出包信息）--------------------------------------
PACMAN=""
if command -v pacman >/dev/null 2>&1; then
    PACMAN="$(command -v pacman)"
elif [ -x "$TOOLS/usr/bin/pacman" ]; then
    PACMAN="$TOOLS/usr/bin/pacman"
    export LD_LIBRARY_PATH="$TOOLS/usr/lib/x86_64-linux-gnu${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
fi
if [ -n "$PACMAN" ]; then
    printf '[options]\nArchitecture = x86_64\nSigLevel = Never\n' >"$WORK/pacman.conf"
    CHKROOT="$WORK/checkroot"
    mkdir -p "$CHKROOT/var/lib/pacman"
    echo "--- pacman -Qip 校验 ---"
    "$PACMAN" --config "$WORK/pacman.conf" --root "$CHKROOT" \
        --dbpath "$CHKROOT/var/lib/pacman" -Qip "$OUT" 2>&1 | head -15 || true
fi
